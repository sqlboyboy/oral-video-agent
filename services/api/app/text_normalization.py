@lru_cache(maxsize=1)
def _opencc_converter():
    try:
        from opencc import OpenCC  # type: ignore
    except Exception:
        return None
    try:
        return OpenCC("t2s")
    except Exception:
        return None


def to_simplified_chinese(text: str) -> str:
    if not text:
        return text
    converter = _opencc_converter()
    if converter is not None:
        return converter.convert(text)
    simplified = text
    for source, target in _PHRASE_REPLACEMENTS:
        simplified = simplified.replace(source, target)
    return simplified.translate(_CHAR_MAP)
